import type { DutyCard, DutyKind, Effects } from './types.ts';

// Story content that sits on top of the ordinary scenario deck:
//
//   SEQUELS       Cards that only appear because of an earlier choice.
//   CONSEQUENCES  Which choice plants which sequel, and how many months later.
//   SET_PIECES    Cards that arrive on fixed months of the term.
//   HEARINGS      Cards a hostile Congress sends in year three, ending in a vote.
//
// None of these are in the shuffled deck; the engine deals them in.

function two(
  id: string,
  kind: DutyKind,
  title: string,
  because: string,
  text: string,
  good: [label: string, effects: Effects, result: string],
  vain: [label: string, effects: Effects, result: string],
  ignore: [stability: number, text: string],
  cost = 1,
): DutyCard {
  return {
    id,
    kind,
    title,
    because,
    text,
    cost,
    options: [
      { label: good[0], effects: good[1], result: good[2] },
      { label: vain[0], effects: vain[1], result: vain[2] },
    ],
    ignore: { stability: ignore[0], text: ignore[1] },
  };
}

function one(
  id: string,
  kind: DutyKind,
  title: string,
  because: string,
  text: string,
  option: [label: string, effects: Effects, result: string],
  ignore: [stability: number, text: string],
  cost = 2,
): DutyCard {
  return {
    id,
    kind,
    title,
    because,
    text,
    cost,
    options: [{ label: option[0], effects: option[1], result: option[2] }],
    ignore: { stability: ignore[0], text: ignore[1] },
  };
}

