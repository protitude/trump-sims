/** The next `n` affirmations, reshuffling once the deck runs out. */
export function nextAffirmations(n: number): string[] {
  const out: string[] = [];
  while (out.length < n) {
    if (deck.length === 0) {
      deck = [...AFFIRMATIONS];
      for (let i = deck.length - 1; i > 0; i--) {
        const j = Math.floor(Math.random() * (i + 1));
        [deck[i], deck[j]] = [deck[j], deck[i]];
      }
    }
    out.push(deck.pop()!);
  }
  return out;
}
